#!/usr/bin/env python3
"""Verify Chapter 5 sources and rebuild its tables/evidence; no model execution."""
from pathlib import Path
from collections import defaultdict
import csv
import hashlib
import json
import statistics as st

THESIS=Path(__file__).resolve().parents[1]
PROJECT=THESIS.parent
DATA=THESIS/'data/chapter5'
TABLES=THESIS/'tables/chapter5'
DATASETS=('OPS-SAT','SMAP','MSL')
FEATURES={'OPS-SAT':1,'SMAP':25,'MSL':55}
METRICS=('bf_f1','bf_precision','bf_recall','bf_auc','pot_f1','pot_precision','pot_recall','pot_auc')
NAMES={'reference':'Reference','window_only':'Window only','ff_only':'FF only','joint':'Joint'}

def sha(p):
 h=hashlib.sha256()
 with Path(p).open('rb') as stream:
  for chunk in iter(lambda:stream.read(1024*1024),b''):h.update(chunk)
 return h.hexdigest()

def stats(values):
 return dict(mean=st.mean(values),sd=st.stdev(values),min=min(values),max=max(values),n=len(values))

def dataset_tex(name):return r'\acs{'+name+'}'
def number(value,places=2):return r'\num{'+f'{value:.{places}f}'+'}'
def uncertain(values,percent=False,places=2):
 scale=100 if percent else 1
 return r'\('+number(st.mean(values)*scale,places)+r'\pm'+number(st.stdev(values)*scale,places)+r'\)'
def write_table(name,lines):
 headers={
  'endpoints.tex':(r'@{}llrrrr@{}',r'Dataset & Reduction & \(w\) & \(d_{\mathrm{ff}}\) & BF200 F1 & \acs{POT} F1 \\'),
  'operating-points.tex':(r'@{}lllrrr@{}',r'Dataset & Setting & Method & Precision & Recall & AUC-PA \\'),
  'resources.tex':(r'@{}llrrrr@{}',r'Dataset & Setting & Parameters & Weight KiB & MAC/window & Forward ms \\')}
 spec,header=headers[name]
 body=[r'\begin{tabular}{'+spec+'}',r'\toprule',header,r'\midrule',*lines,r'\bottomrule',r'\end{tabular}']
 (TABLES/name).write_text('% Generated by scripts/prepare_chapter5.py from data/chapter5/runs.csv.\n'+'\n'.join(body)+'\n')


def main():
 DATA.mkdir(parents=True,exist_ok=True);TABLES.mkdir(parents=True,exist_ok=True)
 with (DATA/'runs.csv').open() as stream:raw=list(csv.DictReader(stream))
 assert len(raw)==270
 groups=defaultdict(list);rows=[];source_hashes=defaultdict(lambda:defaultdict(set));audits=[]
 for r in raw:
  for k in ('window','feedforward','seed','epochs'):r[k]=int(r[k])
  for k in METRICS+('parameters','macs','latency_ms'):r[k]=float(r[k])
  p=PROJECT/r['report_file'];assert sha(p)==r['report_sha256'],p
  report=json.loads(p.read_text());profile=report['profile']
  assert (profile['identifier'],profile['seed'],profile['window_sz'],profile['dim_feedforward'])==(r['identifier'],r['seed'],r['window'],r['feedforward'])
  assert r['epochs']==50 and len(report['training']['records'])==50
  assert report['checkpoint']['sha256']==r['checkpoint_sha256']
  for method in ('bf','pot'):
   saved=report['original_paper_evaluation']['metrics'][method]
   for suffix in ('f1','precision','recall'):
    assert saved[method+'_'+suffix]==r[method+'_'+suffix]
   assert saved[method+'_ROC/AUC']==r[method+'_auc']
   tp,tn,fp,fn=[saved[method+'_'+k] for k in ('TP','TN','FP','FN')]
   assert abs(.5*(tp/(tp+fn)+tn/(tn+fp))-r[method+'_auc'])<1e-9
  f=FEATURES[r['dataset']];h=r['feedforward']
  assert r['parameters']==82*f*f+47*f+(12*f+3)*h
  assert report['model_statistics']['trainable_weight_bytes']==4*r['parameters']
  assert report['model_statistics']['parameters_total']==r['parameters']
  assert report['model_statistics']['compute_estimate']['macs_per_window_batch1']==r['macs']
  for k,v in report['source'].items():
   if 'sha256' in k:source_hashes[r['campaign']][k].add(v)
  r['_report']=report;rows.append(r);groups[(r['dataset'],r['window'],r['feedforward'])].append(r)
 assert len(groups)==90
 cells=[]
 for (ds,w,h),group in sorted(groups.items()):
  assert len(group)==3 and {r['seed'] for r in group}=={2026,2027,2028}
  assert len({r['campaign'] for r in group})==1
  cells.append({'dataset':ds,'window':w,'feedforward':h,'campaign':group[0]['campaign'],
                **{k:stats([r[k] for r in group]) for k in METRICS+('parameters','macs','latency_ms')}})
 corners={};deltas=[];interactions=[];design={};resources={}
 for ds in DATASETS:
  part=[r for r in rows if r['dataset']==ds];ws=sorted({r['window'] for r in part});hs=sorted({r['feedforward'] for r in part})
  assert len(part)==90 and len(ws)==6 and len(hs)==5
  W,H=max(ws),max(hs)
  design[ds]={'windows':ws,'feedforwards':hs,'seeds':[2026,2027,2028],'epochs':50,
              'reference':[W,H],'campaign_runs':{c:sum(r['campaign']==c for r in part) for c in ('v10','v12')}}
  design[ds]['features']=FEATURES[ds]
  for key in ('num_layers','batch_sz','lr','pot_q','shuffle','padding','num_workers','downsample'):
   values={json.dumps(r['_report']['profile'].get(key)) for r in part};assert len(values)==1,(ds,key)
   design[ds][key]=part[0]['_report']['profile'].get(key)
  corners[ds]={}
  for name,w,h in [('reference',W,H),('window_only',min(ws),H),('ff_only',W,min(hs)),('joint',min(ws),min(hs))]:
   g=sorted(groups[(ds,w,h)],key=lambda r:r['seed']);assert {r['campaign'] for r in g}=={'v10'}
   corners[ds][name]={'window':w,'feedforward':h,'campaign':'v10','identifiers':[r['identifier'] for r in g],
                     **{k:stats([r[k] for r in g]) for k in METRICS+('parameters','macs','latency_ms')}}
  baseline=sorted(groups[(ds,W,H)],key=lambda r:r['seed'])
  for name,c in corners[ds].items():
   g=sorted(groups[(ds,c['window'],c['feedforward'])],key=lambda r:r['seed'])
   for metric in METRICS:
    a=[100*(r[metric]-b[metric]) for r,b in zip(g,baseline)]
    deltas.append({'dataset':ds,'comparison':name,'metric':metric,**stats(a),'values':a})
  for metric in ('bf_f1','pot_f1'):
   other=[sorted(groups[(ds,corners[ds][name]['window'],corners[ds][name]['feedforward'])],key=lambda r:r['seed']) for name in ('joint','window_only','ff_only','reference')]
   a=[100*(j[metric]-w[metric]-h[metric]+b[metric]) for j,w,h,b in zip(*other)]
   interactions.append({'dataset':ds,'metric':metric,**stats(a),'values':a})
  resources[ds]={}
  for name in ('reference','window_only','ff_only','joint'):
   c=corners[ds][name];p=c['parameters']['mean'];m=c['macs']['mean']
   resources[ds][name]={'parameters':int(p),'weight_bytes':int(4*p),'MACs':int(m),'FLOPs':int(2*m),
                       'parameter_reduction_pct':100*(1-p/corners[ds]['reference']['parameters']['mean']),
                       'MAC_reduction_pct':100*(1-m/corners[ds]['reference']['macs']['mean'])}
 # Table body: 4 geometrically defined endpoints, never metric-selected winners.
 lines=[]
 for ds in DATASETS:
  if lines:lines.append(r'\addlinespace')
  for name,c in corners[ds].items():
   g=groups[(ds,c['window'],c['feedforward'])]
   lines.append(' & '.join([dataset_tex(ds),NAMES[name],number(c['window'],0),number(c['feedforward'],0),
                            uncertain([r['bf_f1'] for r in g],True),uncertain([r['pot_f1'] for r in g],True)])+r' \\')
 write_table('endpoints.tex',lines)
 lines=[]
 for ds in DATASETS:
  if lines:lines.append(r'\addlinespace')
  for name in ('reference','joint'):
   c=corners[ds][name];g=groups[(ds,c['window'],c['feedforward'])]
   for method,label in (('bf','BF200'),('pot',r'\acs{POT}')):
    lines.append(' & '.join([dataset_tex(ds),NAMES[name],label]+[uncertain([r[method+'_'+key] for r in g],True) for key in ('precision','recall','auc')])+r' \\')
 write_table('operating-points.tex',lines)
 lines=[]
 for ds in DATASETS:
  if lines:lines.append(r'\addlinespace')
  for name in ('reference','joint'):
   c=corners[ds][name];g=groups[(ds,c['window'],c['feedforward'])]
   lines.append(' & '.join([dataset_tex(ds),NAMES[name],r'\num{'+str(int(c['parameters']['mean']))+'}',
                            number(4*c['parameters']['mean']/1024),r'\num{'+str(int(c['macs']['mean']))+'}',
                            uncertain([r['latency_ms'] for r in g],False,3)])+r' \\')
 write_table('resources.tex',lines)
 report={'date':'2026-11-08','metric_definition':'original BF200 and POT, both PA; AUC fields are binary AUC-PA',
         'source_csv_sha256':sha(DATA/'runs.csv'),'raw_reports_verified':270,'AUC_balanced_accuracy_checks':540,
         'uncertainty':'Tables mean/sample SD; plotted slices mean/minimum–maximum over 3 seeds; fixed data splits.',
         'design':design,'corners':corners,'paired_endpoint_deltas_pp':deltas,'factorial_interactions_pp':interactions,
         'resources':resources,'source_hashes':{c:{k:sorted(v) for k,v in d.items()} for c,d in source_hashes.items()},
         'campaign_scope':'All four endpoint configurations in each dataset are v10. The 90-cell overview combines disjoint v10/v12 cells; unequal source revisions do not certify full numerical identity.',
         'timing':'A100 batch1 FP32, 10 warmups/50 synchronized wall-clock calls; tables mean/sample SD of 3 seed-specific medians. NASA timing uses synthetic input; OPS-SAT uses first real test window.'}
 (DATA/'evidence.json').write_text(json.dumps(report,indent=2,allow_nan=False)+'\n')
 print('Verified 270 raw reports, 90 cells, 540 AUCs; generated 3 table bodies and evidence.json')

if __name__=='__main__':main()
